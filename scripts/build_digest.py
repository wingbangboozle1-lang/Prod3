#!/usr/bin/env python3
"""Render the suggestion index inside DIRECTION.md from data/suggestions.json.

The digest table between the sg-index markers used to be hand-maintained and
drifted twice: paraphrased titles (session a25ccde6's I-01 class) and, on
2026-11-20, four rows carrying the register's own SG-27..SG-30 ids with
different meanings (FLG-025 family). A generated block cannot drift: the JSON
is the single source of truth and `--check` fails when the block is stale.

Usage:
  python3 scripts/build_digest.py          # rewrite the block in DIRECTION.md
  python3 scripts/build_digest.py --check  # exit 1 if the block is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- sg-index:generated by scripts/build_digest.py — do not edit this block by hand -->"
END = "<!-- sg-index:end -->"


def render_rows() -> str:
    data = json.loads((ROOT / "data" / "suggestions.json").read_text(encoding="utf-8"))
    rows = []
    for s in data["suggestions"]:
        sid = s["id"]
        title = s["title"].replace("|", "\\|")
        status = s.get("status", "?")
        if s.get("retired_note"):
            status = f"retired — {s['retired_note']}"
        owner = s.get("decision_owner", "—") or "—"
        rows.append(f"| {sid} | {title} | {status} | {owner} |")
    header = ("| # | Suggestion | Status | Decided by |\n"
              "|---|-----------|--------|------------|")
    return "\n".join([header] + rows)


def main() -> None:
    path = ROOT / "DIRECTION.md"
    text = path.read_text(encoding="utf-8")
    try:
        pre, rest = text.split(START, 1)
        block, post = rest.split(END, 1)
    except ValueError:
        print("FAIL: sg-index markers not found in DIRECTION.md")
        sys.exit(1)
    want = "\n" + render_rows() + "\n"
    if "--check" in sys.argv:
        if block != want:
            print("FAIL: DIRECTION.md suggestion digest is stale")
            print("Run: python3 scripts/build_digest.py")
            sys.exit(1)
        print("OK: DIRECTION.md suggestion digest matches data/suggestions.json")
        return
    path.write_text(pre + START + want + END + post, encoding="utf-8")
    print("wrote DIRECTION.md digest block")


if __name__ == "__main__":
    main()
